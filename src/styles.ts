// 诗影工坊 · 艺术风格配方卡（Art Style Recipes）
// 借鉴 huashu-art-motion「35 种风格配方卡」思路：
//   每种风格 = 风格锚点（画面语言 / 色调 / 材质）+ 动效母题（画面如何运动）
// 画面工序（AI 出图）按所选风格重写 STYLE_ANCHOR；
// 动效工序（图生视频）按所选风格的 motionHint 调整运动描述；
// svg 离线引擎当前仅使用默认水墨调色板，其余风格需走 AI 出图通道。
// ════════════════════════════════════════════════════════════════

export interface ArtStyle {
  id: string;
  label: string;
  /** 一句话简介，工作台 chip 副标题用 */
  hint: string;
  /** 画面风格锚点：替换 prompts.ts 的 STYLE_ANCHOR，约束画风 / 色调 / 材质，不引入具体物件 */
  styleAnchor: string;
  /** 动效母题：描述该风格下画面元素如何自然运动，注入图生视频 prompt */
  motionHint: string;
  /** 代表色（仅用于工作台 chip 视觉标识，不参与生成） */
  swatch: string;
}


/** 取风格配方卡；未知 id 回退默认水墨风格 */
export function getArtStyle(id: string | undefined | null): ArtStyle {
  if (id && ART_STYLES[id]) return ART_STYLES[id]!;
  return ART_STYLES[DEFAULT_STYLE_ID]!;
}

